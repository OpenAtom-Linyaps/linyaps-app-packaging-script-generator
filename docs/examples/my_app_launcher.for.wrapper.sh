#!/bin/bash
# ============================================================
# 嵌套啟動腳本範例 (Nested Script Example)
# ------------------------------------------------------------
# 用途：在 wrapper 與真正二進制之間插入自訂啟動邏輯
# 放置：工程根目錄，與 pak_linyaps.sh 同級
# 使用：./pak_linyaps.sh --nested_script=my_app_launcher.sh ...
# ------------------------------------------------------------
# 重要約定：
#   - 檔案必須以 ${wrapper} 佔位符引用同目錄的 wrapper（會被替換成真實檔名）
#   - 執行環境：腳本被複製到 <prefix>/bin/ 下，與 wrapper 同目錄
#   - 可依賴 wrapper 已設定好的相對路徑 / 環境
# ============================================================

# 宣告 shell（保留 wrapper 傳入的參數）
exec "${wrapper}" "$@"
